# save_docs.py — 규정 10건을 벡터DB에 저장 (R1·R2)
from rag_config import collection

# 가상의 '한빛페이 보안 규정' 10건 — 실습용 가짜 데이터 (실제 사내 문서 금지)
DOCS = [
    "비밀번호는 12자 이상으로 하고 영문 대소문자, 숫자, 특수문자를 섞어야 한다.",
    "비밀번호는 90일마다 변경하고 최근 3회 사용한 비밀번호는 재사용할 수 없다.",
    "회사 PC에는 승인받지 않은 USB 등 외부 저장장치를 연결할 수 없다.",
    "피싱 의심 메일을 받으면 열지 말고 보안팀(내선 1234)에 즉시 신고한다.",
    "자리를 비울 때는 화면 잠금을 하며, 화면 보호기는 5분 이내로 설정한다.",
    "개인정보가 담긴 파일은 반드시 암호화하여 저장하고 외부 전송을 금지한다.",
    "사내 계정과 비밀번호는 동료를 포함해 누구와도 공유할 수 없다.",
    "업무용 소프트웨어는 보안팀 사전 승인 후에만 설치할 수 있다.",
    "재택근무 시에는 반드시 회사 VPN에 접속한 뒤 업무 시스템을 사용한다.",
    "중요 업무 자료는 주 1회 이상 지정된 백업 서버에 백업한다.",
]

# upsert = 있으면 덮어쓰고 없으면 넣기 → 여러 번 실행해도 중복이 안 생긴다 (R2)
collection.upsert(
    ids=[f"rule-{i+1:02d}" for i in range(len(DOCS))],           # rule-01 ~ rule-10
    documents=DOCS,
    metadatas=[{"source": f"보안규정 {i+1}조"} for i in range(len(DOCS))],   # 메타데이터 = 문서에 붙이는 꼬리표(여기선 출처 조항)
)

print("저장된 문서 수:", collection.count())
